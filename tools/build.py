"""Compiles src/ with the original compiler and links the hook DLL.

    build.py        the hook DLL, build/th06.dll
    build.py exe    the standalone game, build/th06.exe

FEAT (a comma-separated list) turns on optional features in the
standalone game only: `FEAT=frame_cap,english build.py exe` compiles
with /DFEAT_FRAME_CAP=1 /DFEAT_ENGLISH=1. The DLL is always built from
the vanilla code, so it still matches the original.

Every function in config/symbols.csv that src/ defines is hooked: the DLL
overwrites the original function with a jump to the new one. Every other
symbol becomes an absolute symbol at its original address, so new code
calls and reads the original game.

The standalone exe links src/ without src/dll/ but with src/exe/ (the
game's data and global objects, which the DLL takes from the original)
against the real libraries, plus the original's resources. Its objects
are compiled with /DTH06_EXE=1 into their own directory, build/obj_exe
(build/obj_<features> with FEAT): `#ifdef TH06_EXE` guards the game's
globals that src/ defines in the files that own them, so the DLL binds
the original's.
"""
import collections, csv, glob, json, os, struct, subprocess, sys

import coff

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OBJ = "build/obj"
OBJ_EXE = "build/obj_exe"  # the vanilla standalone exe's
SJIS = "build/src"  # src/ converted to Shift-JIS
DLL = "build/th06.dll"
EXE = "build/th06.exe"
EXE_MAP = "build/th06_exe.map"  # the DLL's map is build/th06.map
ORIGINAL = "build/th06_102h.exe"
CFLAGS = ["/Od", "/Ob1", "/G5", "/GX", "/Op", "/Oi", "/GS", "/Gy", "/GF"]
GLUE_PREFIX = "dll_"  # objects from src/dll/, the DLL's own code
DLL_ONLY, EXE_ONLY = "dll", "exe"  # subdirectories of src/ only one target builds
TIMEOUT = 60  # cl spins forever after a fatal error
# The exe's optional features: FEAT name, macro and what it needs.
FEATURES = {"frame_cap": "FEAT_FRAME_CAP", "english": "FEAT_ENGLISH"}
GENERATED = "build/feat"  # headers generated for the features
ENGLISH = "orig/th06e"  # scripts/english.py's output

ENV = dict(
    os.environ,
    WINEPREFIX=os.environ.get("WINEPREFIX", os.path.join(ROOT, ".wine")),
    WINEDEBUG=os.environ.get("WINEDEBUG", "-all"),
    INCLUDE=r"C:\dx8\include;C:\msvc7\include;C:\psdk\Include",
    LIB=r"C:\dx8\lib;C:\msvc7\lib;C:\msvc7\PlatformSDK\Lib;C:\psdk\Lib",
)


def win(path):
    return path.replace("/", "\\")


def tool(name, *args):
    cmd = ["wine", rf"C:\msvc7\bin\{name}.exe", "/nologo", *args]
    try:
        r = subprocess.run(cmd, env=ENV, timeout=TIMEOUT, capture_output=True, text=True, errors="replace")
    except subprocess.TimeoutExpired:
        sys.exit(f"{name} timed out (fatal error?): {' '.join(args)}")
    out = "\n".join(l for l in r.stdout.splitlines() if l.strip() and not l.endswith(".cpp"))
    if out:
        print(out)
    if r.returncode:
        sys.exit(r.returncode)


def read_symbols():
    with open("config/symbols.csv") as f:
        return {s: int(r["address"], 16) for r in csv.DictReader(f) for s in r["symbol"].split()}


def to_sjis(text):
    """Encodes `text` as Shift-JIS for cl.

    cl reads source bytes as single-byte characters, so a double-byte
    character whose second byte is 0x5c ("能", "表", "ソ") would end in an
    escape inside a string literal: that byte is doubled.
    """
    out = bytearray()
    for ch in text:
        b = ch.encode("cp932")
        out += b
        if len(b) == 2 and b[1] == 0x5C:
            out += b"\\"
    return bytes(out)


def features():
    """The features FEAT asks for, sorted."""
    names = sorted({f.strip() for f in os.environ.get("FEAT", "").split(",") if f.strip()})
    unknown = [f for f in names if f not in FEATURES]
    if unknown:
        sys.exit(f"unknown FEAT {', '.join(unknown)}; known: {', '.join(FEATURES)}")
    return names


def generate_english_header():
    """Writes build/feat/english.h from orig/th06e/strings.txt: the
    English patch's strings, which stay out of the repository."""
    src = os.path.join(ENGLISH, "strings.txt")
    if not os.path.exists(src):
        sys.exit(f"{src} is missing: run scripts/english.py first")
    out = os.path.join(GENERATED, "english.h")
    os.makedirs(GENERATED, exist_ok=True)
    lines = [b"// Generated by tools/build.py from " + src.encode() + b".", b"#pragma once"]
    with open(src, "rb") as f:
        for line in f.read().splitlines():
            name, _, value = line.partition(b"=")
            literal = value.replace(b"\\", b"\\\\").replace(b'"', b'\\"')
            lines.append(b"#define EN_" + name + b' "' + literal + b'"')
    data = b"\n".join(lines) + b"\n"
    if not os.path.exists(out) or open(out, "rb").read() != data:
        with open(out, "wb") as f:
            f.write(data)


def compile_all(target=DLL, feats=()):
    """Compiles src/ from a Shift-JIS copy in build/src/.

    Sources are UTF-8, but the game's strings are Shift-JIS and MSVC 7
    copies string bytes as they are, so each file is converted first.
    The exe's objects go to their own directory, build/obj_exe, or
    build/obj_<features> with features, and see TH06_EXE.
    An object is rebuilt when its source or any header is newer, or when
    its flags changed: each object directory's flags.json records them.
    """
    if target == DLL:
        obj_dir, defines = OBJ, []
    else:
        obj_dir = "_".join([OBJ, *feats]) if feats else OBJ_EXE
        defines = ["/DTH06_EXE=1"] + ["/D%s=1" % FEATURES[f] for f in feats]
    if "english" in feats:
        generate_english_header()
        defines.append("/I" + win(GENERATED))
    os.makedirs(obj_dir, exist_ok=True)
    for src in glob.glob("src/**/*.*", recursive=True):
        copy = os.path.join(SJIS, os.path.relpath(src, "src"))
        if not os.path.exists(copy) or os.path.getmtime(copy) < os.path.getmtime(src):
            os.makedirs(os.path.dirname(copy), exist_ok=True)
            with open(src, encoding="utf-8") as f:
                text = f.read()
            with open(copy, "wb") as f:
                f.write(to_sjis(text))
    headers = max((os.path.getmtime(h) for h in glob.glob("src/**/*.h", recursive=True)
                   + glob.glob(GENERATED + "/*.h")), default=0)
    record = os.path.join(obj_dir, "flags.json")
    try:
        with open(record) as f:
            built = json.load(f)
    except (OSError, ValueError):
        built = {}
    objs = []
    for src, obj in sources(target, obj_dir):
        rel = os.path.relpath(src, "src")
        objs.append(obj)
        flags = file_flags(src) + defines
        if (os.path.exists(obj) and os.path.getmtime(obj) > max(os.path.getmtime(src), headers)
                and built.get(obj) == flags):
            continue
        print("cl", src)
        # A failed compile exits; drop the entry first so it is retried.
        built.pop(obj, None)
        save_flags(record, built)
        tool("cl", "/c", *flags, "/I" + win(SJIS), "/Fo" + win(obj),
             win(os.path.join(SJIS, rel)))
        built[obj] = flags
    save_flags(record, built)
    return objs


def save_flags(path, built):
    with open(path, "w") as f:
        json.dump(built, f, indent=1, sort_keys=True)


def sources(target=DLL, obj_dir=OBJ):
    """Yields (source, object) for each .cpp in src/ that `target` builds."""
    skip = EXE_ONLY if target == DLL else DLL_ONLY
    for src in sorted(glob.glob(os.path.join(ROOT, "src/**/*.cpp"), recursive=True)):
        rel = os.path.relpath(src, os.path.join(ROOT, "src"))
        if rel.split(os.sep)[0] == skip:
            continue
        yield os.path.relpath(src, ROOT), os.path.join(obj_dir, rel.replace("/", "_")[:-4] + ".obj")


def file_flags(src):
    """The flags for one file: CFLAGS, changed by a `// cflags: ...` first
    line. `/X` adds a flag, `-/X` removes a default one."""
    with open(src) as f:
        first = f.readline()
    changes = first.split(":", 1)[1].split() if first.startswith("// cflags:") else []
    flags = [f for f in CFLAGS if "-" + f not in changes]
    return flags + [c for c in changes if not c.startswith("-")]


def write_hooks(objs, symbols):
    """Writes the hook table and the symbols that point into the original.

    The linker rejects calls to absolute symbols, so each original function
    that new code calls gets a thunk instead: push <address>; ret. It
    leaves every register intact, whatever the calling convention.
    """
    defined, code, undefined, called, glue = set(), set(), set(), set(), set()
    for path in objs:
        obj = coff.Object(path)
        for s in obj.externals():
            if s.section <= 0:
                undefined.add(s.name)
                if os.path.basename(path).startswith(GLUE_PREFIX):
                    glue.add(s.name)
                continue
            defined.add(s.name)
            if obj.sections[s.section - 1].flags & coff.CODE:
                code.add(s.name)
        for sec in obj.sections:
            called.update(obj.symbols[i].name for _, i, t in sec.relocs if t == coff.REL32)
    # Data that src/ defines, such as vtables, is never hooked. Functions
    # the linker folded into one share an address; one hook covers them.
    hooks = sorted({symbols[n]: n for n in sorted(code & symbols.keys())}.items())
    # Imports the hook installer itself uses stay real imports: it runs
    # from DllMain and should not rely on the game's import table.
    external = {n: a for n, a in symbols.items()
                if n in undefined - defined and not (n.startswith("__imp_") and n in glue)}

    table, table_relocs = bytearray(), []
    for addr, name in hooks:
        table_relocs.append((len(table) + 4, name, coff.DIR32))
        table += struct.pack("<II", addr, 0)
    table += bytes(8)
    thunks, entry = bytearray(), {"_g_Hooks": (1, 0)}
    for name, addr in external.items():
        if name in called:
            entry[name] = (2, len(thunks))
            thunks += struct.pack("<BIB", 0x68, addr, 0xC3).ljust(8, b"\xcc")
    absolute = {n: a for n, a in external.items() if n not in entry}
    # Functions with exception handling address the handler chain as
    # fs:[__except_list]; the CRT defines it as the absolute value 0.
    if "__except_list" in undefined:
        absolute["__except_list"] = 0

    path = os.path.join(OBJ, "hooks.obj")
    coff.write_object(path, [(".rdata", coff.RDATA, bytes(table), table_relocs),
                             (".text", coff.TEXT, bytes(thunks), [])],
                      entry, [n for _, n in hooks], absolute)
    print(f"{len(hooks)} hooked, {len(external)} used from the original")
    return path


def link_order(objs, symbols):
    """Sorts the game's objects into the original's order: by the lowest
    original address of a function that only that object defines, so an
    inline function other objects also emit doesn't pull it forward.
    Objects that define no such function (data, globals) go last, in
    their given order."""
    code = {}
    for path in objs:
        obj = coff.Object(path)
        code[path] = {s.name for s in obj.externals()
                      if s.section > 0 and obj.sections[s.section - 1].flags & coff.CODE}
    count = collections.Counter(n for names in code.values() for n in names)

    def first(path):
        return min((symbols[n] for n in code[path] if count[n] == 1 and n in symbols),
                   default=1 << 32)
    return sorted(objs, key=first)


def link_exe(objs, feats=()):
    """Links the standalone game with the libraries the original was built
    with: the static multithreaded CRT, D3DX8 and the import libraries.
    The resources are the original's, or the English exe's (it adds an
    icon) with the English feature."""
    import rsrc
    res = os.path.join(os.path.dirname(objs[0]), "th06.res")
    image = os.path.join(ENGLISH, "th06e.exe") if "english" in feats else ORIGINAL
    rsrc.write_res(res, rsrc.resources(image))
    # Objects and libraries in the original's order: its code and import
    # table put DirectInput first, D3DX8 after the import thunks and the
    # CRT last. uuid's GUID_NULL comes before the CRT's .rdata, and its
    # objects before the CRT's in the Rich header.
    objs = link_order(objs, read_symbols())
    # /OPT:REF and /OPT:ICF as the IDE's release configuration sets them.
    # Without an explicit /OPT:ICF the linker still folds functions, but
    # not identical read-only data.
    tool("link", "/SUBSYSTEM:WINDOWS", "/FIXED", "/OPT:REF", "/OPT:ICF",
         "/NODEFAULTLIB:libc.lib", "/MAP:" + win(EXE_MAP), "/OUT:" + win(EXE), *map(win, objs), win(res),
         "dinput8.lib", "dsound.lib", "d3d8.lib", "d3dx8.lib", "dxguid.lib",
         "winmm.lib", "kernel32.lib", "user32.lib", "gdi32.lib", "uuid.lib", "libcmt.lib")
    copy_header_fields(ORIGINAL, EXE)
    print("linked", EXE)


def copy_header_fields(src, dst):
    """Gives dst the original's link timestamp, the one header field the
    linker has no option for."""
    with open(src, "rb") as f:
        orig = f.read(0x400)
    pe = struct.unpack_from("<I", orig, 0x3C)[0]
    with open(dst, "r+b") as f:
        f.seek(0x3C)
        dpe = struct.unpack("<I", f.read(4))[0]
        f.seek(dpe + 8)
        f.write(orig[pe + 8:pe + 12])


def main():
    os.chdir(ROOT)
    if sys.argv[1:] == ["exe"]:
        feats = features()
        if feats:
            print("features:", ", ".join(feats))
        link_exe(compile_all(EXE, feats), feats)
        return
    objs = compile_all()
    hooks = write_hooks(objs, read_symbols())
    tool("link", "/DLL", "/NODEFAULTLIB", "/ENTRY:DllMain", "/BASE:0x30000000",
         "/MAP:" + win(DLL[:-4] + ".map"), "/OUT:" + win(DLL),
         *map(win, objs), win(hooks), "kernel32.lib", "user32.lib", "winmm.lib")
    print("linked", DLL)


if __name__ == "__main__":
    main()
